const header = "// Code generated by Koala. DO NOT EDIT.\n"
const manifestPath = ".koala/generation.json"

type Options struct {
	LocalPlugins string
	Buf          string
	Strict       bool
	Output       io.Writer
}
type service struct {
	Name, GoName, Import, FileSymbol, Directory string
	Methods                                     []string
	Factory                                     factory
}
type factory struct {
	Import, Name, Signature string
	Methods                 map[string]bool
}
type manifest struct {
	Version   int               `json:"version"`
	Contracts string            `json:"contracts"`
	Input     string            `json:"input"`
	Outputs   map[string]string `json:"outputs"`
}

func command(ctx context.Context, root string, out io.Writer, name string, args ...string) error {
	for attempt := 0; ; attempt++ {
		var diagnostic bytes.Buffer
		cmd := exec.CommandContext(ctx, name, args...)
		cmd.Dir = root
		cmd.Stdout = io.MultiWriter(out, &diagnostic)
		cmd.Stderr = cmd.Stdout
		e := cmd.Run()
		if e == nil {
			return nil
		}
		if attempt >= 3 || !strings.Contains(diagnostic.String(), "resource_exhausted") {
			return fmt.Errorf("%s failed: %w", name, e)
		}
		delay := time.Duration(10*(1<<attempt)) * time.Second
		fmt.Fprintf(out, "Buf rate limit; retrying in %s\n", delay)
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(delay):
		}
	}
}

func bufBinary(explicit, version string) (string, error) {
	if explicit != "" {
		p, e := filepath.Abs(explicit)
		return p, e
	}
	p, e := exec.LookPath("buf")
	if e != nil {
		return "", fmt.Errorf("Buf %s is required; install it or pass --buf /path/to/buf", version)
	}
	return p, nil
}

// Run only writes a registry after descriptors, factory signatures and concrete
// interface compatibility pass. Buf output is staged separately. Existing
// application shells are never overwritten.
func Run(ctx context.Context, root string, o Options) (result error) {
	if o.Output == nil {
		o.Output = io.Discard
	}
	cfg, e := readConfig(root)
	if e != nil {
		return e
	}
	if e = rejectSymlinks(root, []string{"proto", "gen", "internal/service", "internal/bootstrap", ".koala"}); e != nil {
		return e
	}
	outputsTxn := newOutputTransaction(root)
	committed := false
	defer func() {
		if !committed {
			result = errors.Join(result, outputsTxn.rollback())
		}
	}()
	sources, e := protoSources(root, cfg)
	if e != nil {
		return e
	}
	var buf string
	pinned, e := tools.ReadVersions()
	if e != nil {
		return fmt.Errorf("invalid embedded tool versions: %w", e)
	}
	if len(sources) > 0 {
		buf, e = bufBinary(o.Buf, pinned.Buf)
		if e != nil {
			return e
		}
		version, err := exec.CommandContext(ctx, buf, "--version").Output()
		if err != nil || strings.TrimSpace(string(version)) != pinned.Buf {
			return fmt.Errorf("Buf version mismatch: expected %s", pinned.Buf)
		}
	}
	stage, e := os.MkdirTemp("", "koala-gen-")
	if e != nil {
		return e
	}
	defer os.RemoveAll(stage)

	previous, manifestError := readManifest(root)
	if manifestError != nil && !os.IsNotExist(manifestError) {
		return manifestError
	}
	contracts, e := contractHash(root, cfg)
	if e != nil {
		return e
	}
	cached := previous.Contracts == contracts && previous.Version == 1
	if cached {
		for path, want := range previous.Outputs {
			if !strings.HasPrefix(path, "gen/") && path != ".koala/descriptors.bin" {
				continue
			}
			data, err := os.ReadFile(filepath.Join(root, path))
			if err != nil || hash(data) != want {
				cached = false
				break
			}
		}
	}
	var descriptors []byte
	var outputs map[string][]byte
	if cached {
		descriptors, e = os.ReadFile(filepath.Join(root, ".koala/descriptors.bin"))
		if e != nil {
			return e
		}
		outputs = map[string][]byte{}
		for path := range previous.Outputs {
			if strings.HasPrefix(path, "gen/") {
				outputs[path], e = os.ReadFile(filepath.Join(root, path))
				if e != nil {
					return e
				}
			}
		}
		fmt.Fprintln(o.Output, "Reusing verified transport artifacts for unchanged contracts")
	} else if len(sources) == 0 {
		outputs = map[string][]byte{}
		if e = outputsTxn.install(outputs, previous); e != nil {
			return e
		}
		fmt.Fprintln(o.Output, "No protobuf contracts; generating an empty registry")
	} else {
		if e = command(ctx, root, o.Output, buf, "lint"); e != nil {
			return e
		}
		if e = command(ctx, root, o.Output, buf, "build", "-o", filepath.Join(stage, "descriptors.bin"), "--as-file-descriptor-set"); e != nil {
			return e
		}
		descriptors, e = os.ReadFile(filepath.Join(stage, "descriptors.bin"))
		if e != nil {
			return e
		}
		args := []string{"generate", "--output", stage}
		if o.LocalPlugins != "" {
			template, e := localTemplate(root, o.LocalPlugins, stage, pinned)
			if e != nil {
				return e
			}
			args = append(args, "--template", template)
		}
		if e = command(ctx, root, o.Output, buf, args...); e != nil {
			return e
		}
		outputs, e = generatedFiles(filepath.Join(stage, "gen"))
		if e != nil {
			return e
		}
		if spec, ok := outputs["gen/openapi/api.swagger.json"]; ok {
			if e = validateSpec(spec); e != nil {
				return e
			}
		}
		if e = outputsTxn.install(outputs, previous); e != nil {
			return fmt.Errorf("transport output update failed: %w", e)
		}
	}
	services, e := servicesFrom(root, cfg, descriptors)
	if e != nil {
		return e
	}
	if len(sources) > 0 {
		fmt.Fprintln(o.Output, "Buf transport outputs updated; registry checks follow")
		if e = command(ctx, root, o.Output, "go", "build", "-mod=mod", "./gen/go/..."); e != nil {
			return e
		}
	}
	factories, e := discover(ctx, root, cfg, services)
	if e != nil {
		return e
	}
	for i := range services {
		s := &services[i]
		f, ok := factories[s.Name]
		if !ok {
			if o.Strict {
				return fmt.Errorf("%s: no factory; strict generation requires implemented services", s.Name)
			}
			if e = scaffold(root, cfg, *s); e != nil {
				return e
			}
		} else {
			s.Factory = f
		}
	}
	factories, e = discover(ctx, root, cfg, services)
	if e != nil {
		return e
	}
	for i := range services {
		s := &services[i]
		f, ok := factories[s.Name]
		if !ok {
			return fmt.Errorf("%s: factory was not discovered", s.Name)
		}
		s.Factory = f
		for _, m := range s.Methods {
			if !f.Methods[m] {
				if o.Strict {
					return fmt.Errorf("%s/%s: inherited Unimplemented method", s.Name, m)
				}
				fmt.Fprintf(o.Output, "warning: %s/%s inherits Unimplemented\n", s.Name, m)
			}
		}
	}
	openAPIImport := ""
	if _, ok := outputs["gen/openapi/api.swagger.json"]; ok {
		module, err := ApplicationImportPath(root)
		if err != nil {
			return err
		}
		openAPIImport = module + "/gen/openapi"
		embedSource := []byte(header + "package openapi\n\nimport _ \"embed\"\n\n//go:embed api.swagger.json\nvar Document []byte\n")
		outputs["gen/openapi/openapi_gen.go"] = embedSource
		if e = outputsTxn.writeOwned("gen/openapi/openapi_gen.go", embedSource, previous); e != nil {
			return e
		}
	}
	registry, e := registrySource(cfg, services, openAPIImport)
	if e != nil {
		return e
	}
	outputs[cfg.Registry.Output] = registry
	outputs[".koala/descriptors.bin"] = descriptors
	if e = outputsTxn.writeOwned(".koala/descriptors.bin", descriptors, previous); e != nil {
		return e
	}
	if e = outputsTxn.writeOwned(cfg.Registry.Output, registry, previous); e != nil {
		return e
	}
	if e = command(ctx, root, o.Output, "go", "build", "-mod=mod", "./internal/bootstrap"); e != nil {
		return fmt.Errorf("generated registry failed its consumer build: %w", e)
	}
	input, e := inputHash(ctx, root, cfg, services)
	if e != nil {
		return e
	}
	m := manifest{Version: 1, Contracts: contracts, Input: input, Outputs: map[string]string{}}
	for path, b := range outputs {
		m.Outputs[path] = hash(b)
	}
	b, _ := json.MarshalIndent(m, "", "  ")
	if e = outputsTxn.write(manifestPath, append(b, '\n')); e != nil {
		return e
	}
	committed = true
	fmt.Fprintln(o.Output, "Generated service registry and freshness manifest")
	return nil
}
func servicesFrom(root string, cfg Config, b []byte) ([]service, error) {
	var set descriptorpb.FileDescriptorSet
	if e := proto.Unmarshal(b, &set); e != nil {
		return nil, e
	}
	excluded := map[string]bool{}
	for _, n := range cfg.Exclude {
		excluded[n] = true
	}
	module, e := ApplicationImportPath(root)
	if e != nil {
		return nil, e
	}
	var result []service
	for _, file := range set.File {
		if _, e := os.Stat(filepath.Join(root, cfg.ProtoRoot, filepath.FromSlash(file.GetName()))); e != nil {
			continue
		}
		for _, desc := range file.Service {
			name := file.GetPackage() + "." + desc.GetName()
			if excluded[name] {
				delete(excluded, name)
				continue
			}
			pkg := strings.Split(file.GetOptions().GetGoPackage(), ";")[0]
			expected := module + "/gen/go/" + filepath.ToSlash(filepath.Dir(file.GetName()))
			if pkg != expected {
				return nil, fmt.Errorf("%s: go_package must be %s", name, expected)
			}
			s := service{Name: name, GoName: desc.GetName(), Import: pkg, Directory: strings.ToLower(strings.TrimSuffix(desc.GetName(), "Service")), FileSymbol: "File_" + regexp.MustCompile(`[^A-Za-z0-9]`).ReplaceAllString(file.GetName(), "_")}
			if s.Directory == "" {
				return nil, fmt.Errorf("%s: empty service directory", name)
			}
			for _, m := range desc.Method {
				if m.GetClientStreaming() || m.GetServerStreaming() {
					return nil, fmt.Errorf("%s: streaming RPCs are unsupported", name)
				}
				s.Methods = append(s.Methods, m.GetName())
			}
			result = append(result, s)
		}
	}
	if len(excluded) > 0 {
		return nil, fmt.Errorf("exclude references unknown services")
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Name < result[j].Name })
	return result, nil
}

// ApplicationImportPath resolves a project inside a standalone module or monorepo.
func ApplicationImportPath(root string) (string, error) {
	root, err := filepath.Abs(root)
	if err != nil {
		return "", err
	}
	current := root
	for {
		b, e := os.ReadFile(filepath.Join(current, "go.mod"))
		if e == nil {
			m, err := modfile.Parse(filepath.Join(current, "go.mod"), b, nil)
			if err != nil {
				return "", err
			}
			if m.Module == nil {
				return "", errors.New("go.mod has no module directive")
			}
			rel, e := filepath.Rel(current, root)
			if e != nil {
				return "", e
			}
			name := m.Module.Mod.Path
			if rel != "." {
				name += "/" + filepath.ToSlash(rel)
			}
			return name, nil
		}
		if !os.IsNotExist(e) {
			return "", e
		}
		parent := filepath.Dir(current)
		if parent == current {
			return "", errors.New("go.mod not found")
		}
		current = parent
	}
}

func discover(ctx context.Context, root string, c Config, services []service) (map[string]factory, error) {
	if _, err := os.Stat(filepath.Join(root, "internal/service")); os.IsNotExist(err) && len(services) == 0 {
		return map[string]factory{}, nil
	}
	patterns := []string{c.ServicePackages}
	for _, s := range services {
		patterns = append(patterns, s.Import)
	}
	pkgs, e := packages.Load(&packages.Config{Context: ctx, Dir: root, BuildFlags: []string{"-mod=mod"}, Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles | packages.NeedImports | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo}, patterns...)
	if e != nil {
		return nil, e
	}
	depImport, depName, _ := splitType(c.DependencyType)
	known := map[string]service{}
	interfaces := map[string]types.Type{}
	for _, s := range services {
		known[s.Name] = s
		for _, p := range pkgs {
			if p.PkgPath == s.Import {
				if obj := p.Types.Scope().Lookup(s.GoName + "Server"); obj != nil {
					interfaces[s.Name] = obj.Type()
				}
			}
		}
	}
	found := map[string]factory{}
	for _, p := range pkgs {
		if !strings.Contains(p.PkgPath, "/internal/service/") {
			continue
		}
		if len(p.Errors) > 0 {
			return nil, fmt.Errorf("factory package %s: %s", p.PkgPath, p.Errors[0].Msg)
		}
		for _, file := range p.Syntax {
			for _, decl := range file.Decls {
				fn, ok := decl.(*ast.FuncDecl)
				if !ok || fn.Doc == nil {
					continue
				}
				mapping := ""
				for _, comment := range fn.Doc.List {
					if strings.HasPrefix(comment.Text, "//koala:service ") {
						if mapping != "" {
							return nil, fmt.Errorf("%s: multiple factory annotations", fn.Name.Name)
						}
						mapping = strings.TrimSpace(strings.TrimPrefix(comment.Text, "//koala:service "))
					}
				}
				if mapping == "" {
					continue
				}
				excluded := false
				for _, name := range c.Exclude {
					if name == mapping {
						excluded = true
					}
				}
				if excluded {
					continue
				}
				if _, ok := known[mapping]; !ok {
					return nil, fmt.Errorf("%s.%s: unknown service annotation %s", p.PkgPath, fn.Name.Name, mapping)
				}
				if _, ok := found[mapping]; ok {
					return nil, fmt.Errorf("%s: duplicate factories", mapping)
				}
				object, ok := p.TypesInfo.Defs[fn.Name].(*types.Func)
				if !ok {
					return nil, fmt.Errorf("%s: unresolved factory", mapping)
				}
				sig := object.Type().(*types.Signature)
				if fn.Recv != nil || !ast.IsExported(fn.Name.Name) || sig.TypeParams().Len() != 0 || sig.Params().Len() != 1 || sig.Results().Len() != 2 || sig.Variadic() {
					return nil, fmt.Errorf("%s: factory must be exported func(*deps.Dependencies) (*Concrete,error)", mapping)
				}
				pointer, ok := sig.Params().At(0).Type().(*types.Pointer)
				if !ok {
					return nil, fmt.Errorf("%s: factory dependency must be a pointer", mapping)
				}
				named, ok := pointer.Elem().(*types.Named)
				if !ok || named.Obj().Pkg() == nil || named.Obj().Pkg().Path() != depImport || named.Obj().Name() != depName {
					return nil, fmt.Errorf("%s: wrong factory dependency type", mapping)
				}
				result, ok := sig.Results().At(0).Type().(*types.Pointer)
				if !ok {
					return nil, fmt.Errorf("%s: factory must return a concrete pointer", mapping)
				}
				concrete, ok := result.Elem().(*types.Named)
				if !ok || concrete.Obj().Pkg().Path() != p.PkgPath || !ast.IsExported(concrete.Obj().Name()) {
					return nil, fmt.Errorf("%s: factory result must be an exported local type", mapping)
				}
				if !types.Identical(sig.Results().At(1).Type(), types.Universe.Lookup("error").Type()) {
					return nil, fmt.Errorf("%s: factory second result must be error", mapping)
				}
				iface := interfaces[mapping]
				if iface == nil || !types.AssignableTo(result, iface) {
					return nil, fmt.Errorf("%s: concrete type does not implement generated server", mapping)
				}
				methods := map[string]bool{}
				methodSet := types.NewMethodSet(result)
				for i := 0; i < methodSet.Len(); i++ {
					method := methodSet.At(i).Obj().(*types.Func)
					receiver := method.Type().(*types.Signature).Recv().Type()
					if ptr, ok := receiver.(*types.Pointer); ok {
						receiver = ptr.Elem()
					}
					inheritedFallback := false
					if named, ok := receiver.(*types.Named); ok {
						inheritedFallback = named.Obj().Pkg() != nil && named.Obj().Pkg().Path() == known[mapping].Import && named.Obj().Name() == "Unimplemented"+known[mapping].GoName+"Server"
					}
					if !inheritedFallback {
						methods[method.Name()] = true
					}
				}
				found[mapping] = factory{Import: p.PkgPath, Name: fn.Name.Name, Signature: types.TypeString(sig, func(p *types.Package) string { return p.Path() }), Methods: methods}
			}
		}
	}
	return found, nil
}
func scaffold(root string, c Config, s service) error {
	depImport, depType, _ := splitType(c.DependencyType)
	directory := filepath.Join(root, "internal/service", s.Directory)
	entries, e := os.ReadDir(directory)
	if e != nil && !os.IsNotExist(e) {
		return e
	}
	if len(entries) > 0 {
		return fmt.Errorf("%s: no mapped factory and service directory already exists; annotate its factory", s.Name)
	}
	source := fmt.Sprintf("// Application-owned service. Koala will never overwrite this file.\npackage service\nimport(pb %q;deps %q)\ntype Service struct{pb.Unimplemented%sServer}\n//koala:service %s\nfunc New(d *deps.%s)(*Service,error){return &Service{},nil}\n", s.Import, depImport, s.GoName, s.Name, depType)
	formatted, e := format.Source([]byte(source))
	if e != nil {
		return e
	}
	if e = os.MkdirAll(directory, 0755); e != nil {
		return e
	}
	f, e := os.OpenFile(filepath.Join(directory, "service.go"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
	if e != nil {
		return e
	}
	_, e = f.Write(formatted)
	return errors.Join(e, f.Close())
}
func registrySource(c Config, services []service, openAPIImport string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header + "package " + c.Registry.Package + "\nimport(\n")
	if len(services) > 0 {
		b.WriteString("\"context\"\n\"fmt\"\n\n")
	}
	b.WriteString("koala \"github.com/bingyuanng/koala\"\n")
	if len(services) > 0 {
		b.WriteString("\"github.com/grpc-ecosystem/grpc-gateway/v2/runtime\"\n\"google.golang.org/grpc\"\n")
	}
	b.WriteString("\n")
	if openAPIImport != "" {
		fmt.Fprintf(&b, "openapi %q\n", openAPIImport)
	}
	depImport, depType, _ := splitType(c.DependencyType)
	fmt.Fprintf(&b, "deps %q\n", depImport)
	helpers := make([]string, len(services))
	usedNames := map[string]bool{}
	for i, s := range services {
		name := "register" + s.GoName
		base := name
		for suffix := 2; usedNames[name]; suffix++ {
			name = fmt.Sprintf("%s%d", base, suffix)
		}
		helpers[i] = name
		usedNames[name] = true
		fmt.Fprintf(&b, "pb%d %q\nsvc%d %q\n", i, s.Import, i, s.Factory.Import)
	}
	b.WriteString(")\n")
	fmt.Fprintf(&b, "func RegisterAll(app *koala.App, d *deps.%s) error {\n", depType)
	fmt.Fprintf(&b, "registrations := []func(*koala.App, *deps.%s) error {\n", depType)
	for _, name := range helpers {
		fmt.Fprintf(&b, "%s,\n", name)
	}
	b.WriteString("}\nfor _, register := range registrations {\nif err := register(app, d); err != nil { return err }\n}\nreturn nil\n}\n")
	for i, s := range services {
		fmt.Fprintf(&b, "\nfunc %s(app *koala.App, d *deps.%s) error {\n", helpers[i], depType)
		fmt.Fprintf(&b, "impl, err := svc%d.%s(d)\nif err != nil { return fmt.Errorf(%q, err) }\n", i, s.Factory.Name, s.Name+": %w")
		fmt.Fprintf(&b, "if impl == nil { return fmt.Errorf(%q) }\n", s.Name+": factory returned nil implementation")
		fmt.Fprintf(&b, `return app.Register(koala.Registration{
Descriptor: pb%d.%s.Services().ByName(%q),
GRPC: func(r grpc.ServiceRegistrar) {
 pb%d.Register%sServer(r, impl)
},
Gateway: func(ctx context.Context, m *runtime.ServeMux, c *grpc.ClientConn) error {
 return pb%d.Register%sHandler(ctx, m, c)
},
})
}
`, i, s.FileSymbol, s.GoName, i, s.GoName, i, s.GoName)
	}
	b.WriteString("\nfunc ValidateConfig(server koala.ServerConfig, requests koala.RequestConfig) error {return koala.ValidateConfig(server, requests")
	for i, s := range services {
		fmt.Fprintf(&b, ",pb%d.%s.Services().ByName(%q)", i, s.FileSymbol, s.GoName)
	}
	b.WriteString(")}\n")
	if openAPIImport != "" {
		b.WriteString("var OpenAPI = openapi.Document\n")
	} else {
		b.WriteString("var OpenAPI []byte\n")
	}
	return format.Source(b.Bytes())
}

func hash(b []byte) string { s := sha256.Sum256(b); return hex.EncodeToString(s[:]) }

func protoSources(root string, c Config) ([]string, error) {
	var files []string
	protoRoot := filepath.Join(root, c.ProtoRoot)
	err := filepath.WalkDir(protoRoot, func(p string, d os.DirEntry, err error) error {
		if p == protoRoot && os.IsNotExist(err) {
			return nil
		}
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(p, ".proto") {
			rel, err := filepath.Rel(root, p)
			if err != nil {
				return err
			}
			files = append(files, rel)
		}
		return nil
	})
	return files, err
}

func contractHash(root string, c Config) (string, error) {
	module, e := ApplicationImportPath(root)
	if e != nil {
		return "", e
	}
	sources, e := protoSources(root, c)
	if e != nil {
		return "", e
	}
	files := append([]string{"koala.yaml", "buf.yaml", "buf.lock", "buf.gen.yaml"}, sources...)
	sort.Strings(files)
	h := sha256.New()
	pinned, e := tools.ReadVersions()
	if e != nil {
		return "", e
	}
	versions, e := json.Marshal(pinned)
	if e != nil {
		return "", e
	}
	fmt.Fprintln(h, module, "koala-generator-v2", hash(versions))
	for _, p := range files {
		b, e := os.ReadFile(filepath.Join(root, p))
		if e != nil {
			return "", e
		}
		fmt.Fprintf(h, "%s\x00%s\x00", p, hash(b))
	}

	return hex.EncodeToString(h.Sum(nil)), nil
}

func inputHash(ctx context.Context, root string, c Config, services []service) (string, error) {
	contracts, e := contractHash(root, c)
	if e != nil {
		return "", e
	}
	h := sha256.New()
	fmt.Fprintln(h, contracts)
	factories, e := discover(ctx, root, c, services)
	if e != nil {
		return "", e
	}
	names := make([]string, 0, len(factories))
	for k := range factories {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, n := range names {
		f := factories[n]
		fmt.Fprintf(h, "%s:%s:%s:%s\n", n, f.Import, f.Name, f.Signature)
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// CheckFresh excludes business method bodies. Factory annotations/signatures,
// protobuf contracts, configurations and generated output bytes are checked.
func CheckFresh(ctx context.Context, root string) error {
	c, e := readConfig(root)
	if e != nil {
		return e
	}
	m, e := readManifest(root)
	if e != nil || m.Version != 1 {
		return fmt.Errorf("generated artifacts missing; run koala gen")
	}
	services, e := servicesFromManifest(root)
	if e != nil {
		return e
	}
	input, e := inputHash(ctx, root, c, services)
	if e != nil {
		return fmt.Errorf("registration inputs invalid; run koala gen: %w", e)
	}
	if input != m.Input {
		return fmt.Errorf("generation inputs are stale; run koala gen")
	}
	for p, want := range m.Outputs {
		b, e := os.ReadFile(filepath.Join(root, p))
		if e != nil || hash(b) != want {
			return fmt.Errorf("generated output %s is missing or changed; run koala gen", p)
		}
	}
	return nil
}

// Retain descriptors as an owned generation output for offline freshness checks.
func servicesFromManifest(root string) ([]service, error) {
	b, e := os.ReadFile(filepath.Join(root, ".koala/descriptors.bin"))
	if e != nil {
		return nil, fmt.Errorf("descriptor snapshot missing; run koala gen")
	}
	c, e := readConfig(root)
	if e != nil {
		return nil, e
	}
	return servicesFrom(root, c, b)
}
func readManifest(root string) (manifest, error) {
	var m manifest
	b, e := os.ReadFile(filepath.Join(root, manifestPath))
	if e != nil {
		return m, e
	}
	e = json.Unmarshal(b, &m)
	if e != nil {
		return m, e
	}
	if m.Outputs["internal/bootstrap/services_gen.go"] == "" || m.Outputs[".koala/descriptors.bin"] == "" {
		return manifest{}, fmt.Errorf("incomplete generation ownership manifest")
	}
	for p, want := range m.Outputs {
		if !safeOutput(p) || len(want) != 64 {
			return manifest{}, fmt.Errorf("invalid generation ownership manifest")
		}
	}
	return m, nil
}
func generatedFiles(root string) (map[string][]byte, error) {
	files := map[string][]byte{}
	e := filepath.WalkDir(root, func(p string, d os.DirEntry, e error) error {
		if e != nil {
			return e
		}
		if d.IsDir() {
			return nil
		}
		b, e := os.ReadFile(p)
		if e != nil {
			return e
		}
		rel, _ := filepath.Rel(root, p)
		target := "gen/" + filepath.ToSlash(rel)
		if !safeOutput(target) {
			return fmt.Errorf("unexpected generated output %s", target)
		}
		files[target] = b
		return nil
	})
	return files, e
}
func atomicWrite(path string, b []byte) error {
	if e := os.MkdirAll(filepath.Dir(path), 0755); e != nil {
		return e
	}
	f, e := os.CreateTemp(filepath.Dir(path), ".koala-*")
	if e != nil {
		return e
	}
	name := f.Name()
	defer os.Remove(name)
	if _, e = f.Write(b); e != nil {
		f.Close()
		return e
	}
	if e = f.Chmod(0644); e != nil {
		f.Close()
		return e
	}
	if e = f.Close(); e != nil {
		return e
	}
	return os.Rename(name, path)
}
func rejectSymlinks(root string, paths []string) error {
	for _, p := range paths {
		full := filepath.Join(root, p)
		for d := full; d != root && strings.HasPrefix(d, root+string(os.PathSeparator)); d = filepath.Dir(d) {
			if info, e := os.Lstat(d); e == nil && info.Mode()&os.ModeSymlink != 0 {
				return fmt.Errorf("refusing symlink path %s", p)
			}
		}
		e := filepath.WalkDir(full, func(path string, d os.DirEntry, e error) error {
			if os.IsNotExist(e) {
				return nil
			}
			if e != nil {
				return e
			}
			if d.Type()&os.ModeSymlink != 0 {
				return fmt.Errorf("refusing symlink %s", path)
			}
			return nil
		})
		if e != nil {
			return e
		}
	}
	return nil
}

func safeOutput(p string) bool {
	if filepath.ToSlash(filepath.Clean(p)) != p || strings.Contains(p, "\\") || filepath.IsAbs(p) {
		return false
	}
	if p == "internal/bootstrap/services_gen.go" || p == ".koala/descriptors.bin" || p == "gen/openapi/api.swagger.json" || p == "gen/openapi/openapi_gen.go" {
		return true
	}
	return strings.HasPrefix(p, "gen/go/") && (strings.HasSuffix(p, ".pb.go") || strings.HasSuffix(p, ".pb.gw.go")) && !strings.Contains(p, "../")
}

// ReportFallbacks rechecks concrete declarations at startup. Business methods
// are inspected for diagnostics, while remaining excluded from freshness hashes.
func ReportFallbacks(ctx context.Context, root string, out io.Writer) error {
	c, e := readConfig(root)
	if e != nil {
		return e
	}
	_, e = readManifest(root)
	if e != nil {
		return e
	}
	services, e := servicesFromManifest(root)
	if e != nil {
		return e
	}
	factories, e := discover(ctx, root, c, services)
	if e != nil {
		return e
	}
	for _, s := range services {
		for _, method := range s.Methods {
			if !factories[s.Name].Methods[method] {
				fmt.Fprintf(out, "warning: %s/%s inherits Unimplemented\n", s.Name, method)
			}
		}
	}
	return nil
}
