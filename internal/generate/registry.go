package generate

import (
	"bytes"
	"fmt"
	"go/format"
)

const header = "// Code generated by Koala. DO NOT EDIT.\n"

func registrySource(cfg Config, services []service, openAPIImport string) ([]byte, error) {
	var source bytes.Buffer
	source.WriteString(header + "package " + registryPackage + "\nimport(\n")
	if len(services) > 0 {
		source.WriteString("\"context\"\n\"fmt\"\n\n")
	}
	source.WriteString("koala \"github.com/bingyuanng/koala\"\n")
	if len(services) > 0 {
		source.WriteString("\"github.com/grpc-ecosystem/grpc-gateway/v2/runtime\"\n\"google.golang.org/grpc\"\n")
	}
	source.WriteString("\n")
	if openAPIImport != "" {
		fmt.Fprintf(&source, "openapi %q\n", openAPIImport)
	}
	dependencyImport, dependencyType, _ := splitType(cfg.DependencyType)
	fmt.Fprintf(&source, "deps %q\n", dependencyImport)
	registrationNames := make([]string, len(services))
	usedNames := map[string]bool{}
	for i, definition := range services {
		name := "register" + definition.GoName
		baseName := name
		for suffix := 2; usedNames[name]; suffix++ {
			name = fmt.Sprintf("%s%d", baseName, suffix)
		}
		registrationNames[i] = name
		usedNames[name] = true
		fmt.Fprintf(&source, "pb%d %q\nsvc%d %q\n", i, definition.Import, i, definition.Factory.Import)
	}
	source.WriteString(")\n")
	fmt.Fprintf(&source, "func RegisterAll(app *koala.App, d *deps.%s) error {\n", dependencyType)
	fmt.Fprintf(&source, "registrations := []func(*koala.App, *deps.%s) error {\n", dependencyType)
	for _, name := range registrationNames {
		fmt.Fprintf(&source, "%s,\n", name)
	}
	source.WriteString("}\nfor _, register := range registrations {\nif err := register(app, d); err != nil { return err }\n}\nreturn nil\n}\n")
	for i, definition := range services {
		fmt.Fprintf(&source, "\nfunc %s(app *koala.App, d *deps.%s) error {\n", registrationNames[i], dependencyType)
		fmt.Fprintf(&source, "impl, err := svc%d.%s(d)\nif err != nil { return fmt.Errorf(%q, err) }\n", i, definition.Factory.Name, definition.Name+": %w")
		fmt.Fprintf(&source, "if impl == nil { return fmt.Errorf(%q) }\n", definition.Name+": factory returned nil implementation")
		fmt.Fprintf(&source, `return app.Register(koala.Registration{
Descriptor: pb%d.%s.Services().ByName(%q),
GRPC: func(r grpc.ServiceRegistrar) {
 pb%d.Register%sServer(r, impl)
},
Gateway: func(ctx context.Context, m *runtime.ServeMux, c *grpc.ClientConn) error {
 return pb%d.Register%sHandler(ctx, m, c)
},
})
}
`, i, definition.FileSymbol, definition.GoName, i, definition.GoName, i, definition.GoName)
	}
	source.WriteString("\nfunc ValidateConfig(server koala.ServerConfig, requests koala.RequestConfig) error {return koala.ValidateConfig(server, requests")
	for i, definition := range services {
		fmt.Fprintf(&source, ",pb%d.%s.Services().ByName(%q)", i, definition.FileSymbol, definition.GoName)
	}
	source.WriteString(")}\n")
	if openAPIImport != "" {
		source.WriteString("var OpenAPI = openapi.Document\n")
	} else {
		source.WriteString("var OpenAPI []byte\n")
	}
	return format.Source(source.Bytes())
}

// registrationOutputs renders bytes only; installation belongs to outputTransaction.
func registrationOutputs(module string, cfg Config, services []service, descriptors []byte, hasOpenAPI bool) (map[string][]byte, error) {
	outputs := map[string][]byte{".koala/descriptors.bin": descriptors}
	openAPIImport := ""
	if hasOpenAPI {
		openAPIImport = module + "/gen/openapi"
		outputs["gen/openapi/openapi_gen.go"] = []byte(header + "package openapi\n\nimport _ \"embed\"\n\n//go:embed api.swagger.json\nvar Document []byte\n")
	}
	registry, err := registrySource(cfg, services, openAPIImport)
	if err != nil {
		return nil, err
	}
	outputs[registryOutput] = registry
	return outputs, nil
}
